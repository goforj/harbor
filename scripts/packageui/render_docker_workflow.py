"""Render the isolated Docker diagnostic workflow from the canonical CI job."""

from pathlib import Path
import re


def main():
    """main keeps isolated diagnostics identical to the maintained Docker acceptance job."""
    root = Path(__file__).resolve().parents[2]
    source = (root / ".github/workflows/ci.yml").read_text()
    match = re.search(r"(?ms)^  docker-adapter:\n.*?(?=^  [a-z][a-z0-9-]*:|\Z)", source)
    if match is None:
        raise ValueError("canonical Docker acceptance job is missing")
    header = """# Generated by scripts/packageui/render_docker_workflow.py; DO NOT EDIT.
name: Docker project diagnostics

on:
  workflow_dispatch:
  # Register feature-branch dispatches without running Docker during pull requests.
  pull_request:
    paths:
      - .github/workflows/docker-project-diagnostics.yml
      - scripts/packageui/render_docker_workflow.py

permissions:
  contents: read

concurrency:
  group: docker-project-diagnostics-${{ github.ref }}
  cancel-in-progress: false

jobs:
"""
    (root / ".github/workflows/docker-project-diagnostics.yml").write_text(header + match.group().rstrip() + "\n")


if __name__ == "__main__":
    main()
